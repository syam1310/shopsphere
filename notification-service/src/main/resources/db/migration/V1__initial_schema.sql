-- Existing populated databases are baselined at version 1 before migration.
CREATE TABLE public.email_jobs (
    id bigint NOT NULL,
    attempts integer NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    event_key character varying(255) NOT NULL,
    message character varying(10000) NOT NULL,
    next_attempt_at timestamp(6) with time zone,
    recipient character varying(255) NOT NULL,
    sent_at timestamp(6) with time zone,
    status character varying(255) NOT NULL,
    subject character varying(255) NOT NULL
);
ALTER TABLE public.email_jobs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.email_jobs_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE public.notifications (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    message character varying(1000) NOT NULL,
    read boolean NOT NULL,
    title character varying(150) NOT NULL,
    type character varying(50) NOT NULL,
    user_id bigint NOT NULL
);
ALTER TABLE public.notifications ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.notifications_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY public.email_jobs
    ADD CONSTRAINT email_jobs_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.notifications
    ADD CONSTRAINT notifications_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.email_jobs
    ADD CONSTRAINT uk_email_job_event UNIQUE (event_key);
